import CryptoKit
import Foundation
import PaspoIDWire
#if canImport(UIKit)
import UIKit
#endif

/// Entry point of the Paspo ID SDK: authenticates the user through the Paspo ID app.
///
/// ```swift
/// let paspo = Paspo(configuration: .init(redirectURL: URL(string: "https://your.app/paspo/callback")!))
///
/// switch await paspo.authenticate(scope: .phones, nonce: try await backend.requestSsoNonce()) {
/// case let .success(authCode): try await backend.signIn(authCode: authCode)
/// case .cancelled, .notInstalled: break
/// case let .failure(error, _): show(error)
/// }
/// ```
///
/// The instance must survive the round trip through the Paspo ID app: keep it on the screen's
/// model or use ``shared``, and route incoming URLs to ``handle(url:)``. One flow runs at a
/// time — starting a new one cancels the previous.
@MainActor
public final class Paspo {
    // MARK: - Shared instance

    private static var sharedInstance: Paspo?

    /// Configures ``shared``. Call once, typically from the app's initializer.
    public static func configure(_ configuration: PaspoConfiguration) {
        sharedInstance = Paspo(configuration: configuration)
    }

    /// Configures ``shared`` from `PaspoID-Info.plist`, the file downloaded from the Paspo admin panel.
    ///
    /// A missing or broken file traps in debug builds with the reason, and leaves ``shared``
    /// non-functional in release builds.
    public static func configure(bundle: Bundle = .main) {
        do {
            configure(try PaspoConfiguration(bundle: bundle))
        } catch {
            assertionFailure("Paspo ID: \(error)")
        }
    }

    /// Process-wide instance configured with ``configure(_:)``.
    ///
    /// Convenient when the flow is started from one place and callbacks arrive in another
    /// (the app's `onOpenURL`). Accessing it before ``configure(_:)`` traps in debug builds
    /// and yields a non-functional instance in release builds.
    public static var shared: Paspo {
        if let sharedInstance { return sharedInstance }
        assertionFailure("Paspo.shared accessed before Paspo.configure(_:)")
        let placeholder = Paspo(configuration: PaspoConfiguration(redirectURL: URL(string: "paspo-unconfigured://")!))
        placeholder.isConfigured = false
        sharedInstance = placeholder
        return placeholder
    }

    // MARK: - State

    /// Current configuration.
    public private(set) var configuration: PaspoConfiguration

    private let urlOpener: PaspoURLOpening
    private let referralStore: PaspoReferralStore
    private var isConfigured = true

    private var pending: PendingRequest?
    private var didLeaveApplication = false
    private let lifecycleObservers = LifecycleObserverBox()

    private struct PendingRequest {
        let state: String
        let privateKey: P256.KeyAgreement.PrivateKey
        let continuation: CheckedContinuation<PaspoAuthResult, Never>
        var timeoutTask: Task<Void, Never>?
        var cancellationTask: Task<Void, Never>?
    }

    // MARK: - Init

    public init(configuration: PaspoConfiguration) {
        self.configuration = configuration
        urlOpener = PaspoSystemURLOpener()
        referralStore = PaspoReferralStore()
        observeLifecycle()
    }

    init(configuration: PaspoConfiguration, urlOpener: PaspoURLOpening, referralStore: PaspoReferralStore) {
        self.configuration = configuration
        self.urlOpener = urlOpener
        self.referralStore = referralStore
    }

    // MARK: - Public API

    /// Runs the SSO flow: opens the Paspo ID consent screen and waits for its outcome.
    ///
    /// Every outcome, including cancellation and a missing Paspo ID app, is reported through
    /// ``PaspoAuthResult``; this method does not throw.
    ///
    /// - Parameters:
    ///   - scope: Profile data to request from the user.
    ///   - nonce: One-time anti-replay value generated by *your backend* for this attempt.
    /// - Returns: The outcome of the flow.
    public func authenticate(scope: PaspoScope, nonce: String) async -> PaspoAuthResult {
        guard isConfigured else {
            return .failure(error: .invalidRequest, message: "Paspo is not configured")
        }
        guard nonce.isEmpty == false else {
            return .failure(error: .invalidRequest, message: "Empty nonce")
        }
        guard configuration.bundleID.isEmpty == false else {
            return .failure(error: .invalidRequest, message: "Empty bundle identifier")
        }

        resolvePending(with: .cancelled)

        guard isPaspoInstalled else {
            if let appClipURL = configuration.appClipURL, Self.canLaunchAppClips {
                let result = await run(scope: scope, nonce: nonce) { appClipLink(appClipURL, carrying: $0) }
                guard case .failure(.serviceUnavailable, _) = result else { return result }
            }
            referralStore.save(nonce: nonce)
            if let page = configuration.landingURL ?? configuration.appStoreURL {
                _ = await urlOpener.open(page)
            }
            return .notInstalled
        }

        return await run(scope: scope, nonce: nonce) { $0 }
    }

    /// Opens the request built for `nonce` and waits for its callback.
    ///
    /// - Parameter link: Turns the `paspo://sso` request into the URL to open.
    /// - Returns: `.failure(.serviceUnavailable)` when the URL could not be opened.
    private func run(scope: PaspoScope, nonce: String, link: (URL) -> URL?) async -> PaspoAuthResult {
        let privateKey = P256.KeyAgreement.PrivateKey()
        let state = UUID().uuidString
        let request = PaspoAuthRequest(
            nonce: nonce,
            clientPublicKeyDER: privateKey.publicKey.derRepresentation,
            bundleID: configuration.bundleID,
            scope: scope,
            redirectURL: configuration.redirectURL,
            state: state,
            referralNonce: referralStore.load()
        )

        guard let url = request.makeURL().flatMap(link) else {
            return .failure(error: .invalidRequest, message: "Failed to build the request URL")
        }

        return await withCheckedContinuation { continuation in
            pending = PendingRequest(state: state, privateKey: privateKey, continuation: continuation)
            didLeaveApplication = false

            Task { [weak self] in
                guard let self else { return }
                let opened = await self.urlOpener.open(url)
                if opened {
                    self.referralStore.clear()
                    self.startTimeout()
                } else {
                    self.resolvePending(with: .failure(error: .serviceUnavailable, message: "Could not open Paspo ID"))
                }
            }
        }
    }

    /// Feeds an incoming URL to the SDK.
    ///
    /// Call from `onOpenURL` / `onContinueUserActivity` (SwiftUI) or the corresponding
    /// `UIApplicationDelegate` / `UISceneDelegate` methods.
    ///
    /// - Returns: `true` when the URL was a Paspo ID callback and has been consumed.
    @discardableResult
    public func handle(url: URL) -> Bool {
        guard isPaspoCallback(url: url), let callback = PaspoAuthCallback.parse(url: url) else { return false }
        guard let pending, pending.state == callback.state else {
            // A stale or forged callback: never resolve a live flow with it.
            return true
        }

        switch callback {
        case .cancelled:
            resolvePending(with: .cancelled)

        case let .failure(_, errorCode):
            let error = PaspoClientError.from(code: errorCode)
            resolvePending(with: error == .cancelled ? .cancelled : .failure(error: error, message: nil))

        case let .success(_, envelope):
            resolvePending(with: decrypt(envelope: envelope, privateKey: pending.privateKey))
        }
        return true
    }

    /// `true` when the Paspo ID app is installed.
    ///
    /// Requires `paspo` in the app's `LSApplicationQueriesSchemes`; without it iOS always
    /// answers `false` and ``authenticate(scope:nonce:)`` reports ``PaspoAuthResult/notInstalled``.
    public var isPaspoInstalled: Bool {
        guard let url = URL(string: "\(PaspoSSOConstants.paspoScheme)://") else { return false }
        return urlOpener.canOpen(url)
    }

    /// `true` when `url` is Paspo ID asking this app to start sign-in.
    ///
    /// Optional entry point: Paspo ID can send users into your sign-in screen. Handle it by
    /// starting a normal ``authenticate(scope:nonce:)`` — the URL carries no other data.
    public func isSignInRequest(url: URL) -> Bool {
        guard isPaspoCallback(url: url),
              let components = URLComponents(url: url, resolvingAgainstBaseURL: false)
        else { return false }
        return components.queryItems?.contains { $0.name == PaspoSSOConstants.signInRequestMarker } ?? false
    }

    /// Abandons the current flow and destroys its ephemeral key.
    ///
    /// Called automatically when a flow completes; call it manually only when dropping a flow
    /// yourself, for example when the user leaves the sign-in screen.
    public func cleanup() {
        resolvePending(with: .cancelled)
    }

    // MARK: - Private

    /// The App Clip link with the request's query appended; the App Clip reads the same query as
    /// `paspo://sso` and answers on the same redirect URL. `client` names the app on the clip's screens.
    private func appClipLink(_ appClipURL: URL, carrying request: URL) -> URL? {
        guard var components = URLComponents(url: appClipURL, resolvingAgainstBaseURL: false),
              let requestItems = URLComponents(url: request, resolvingAgainstBaseURL: false)?.queryItems
        else { return nil }
        var items = components.queryItems ?? []
        if let name = Self.applicationName {
            items.append(URLQueryItem(name: "client", value: name))
        }
        components.queryItems = items + requestItems
        return components.url
    }

    /// Apps launch other apps' App Clips from iOS 17; earlier the link only opens Safari.
    private static var canLaunchAppClips: Bool {
        if #available(iOS 17, macOS 14, *) { return true }
        return false
    }

    private static var applicationName: String? {
        let info = Bundle.main.infoDictionary
        return (info?["CFBundleDisplayName"] as? String) ?? (info?["CFBundleName"] as? String)
    }

    private func decrypt(envelope: PaspoEncryptedEnvelope, privateKey: P256.KeyAgreement.PrivateKey) -> PaspoAuthResult {
        do {
            let payload = try envelope.open(PaspoSSOResult.self, privateKey: privateKey)
            switch payload {
            case let .success(nonce):
                return .success(authCode: nonce)
            case let .failure(errorCode):
                let error = PaspoClientError.from(code: errorCode)
                return error == .cancelled ? .cancelled : .failure(error: error, message: nil)
            }
        } catch {
            return .failure(error: .cryptoError, message: "\(error)")
        }
    }

    private func isPaspoCallback(url: URL) -> Bool {
        configuration.acceptedRedirectURLs.contains { accepted in
            guard url.scheme?.lowercased() == accepted.scheme?.lowercased() else { return false }
            guard (url.host ?? "").lowercased() == (accepted.host ?? "").lowercased() else { return false }
            return normalizedPath(url) == normalizedPath(accepted)
        }
    }

    private func normalizedPath(_ url: URL) -> String {
        let path = url.path
        guard path.hasSuffix("/"), path.count > 1 else { return path }
        return String(path.dropLast())
    }

    private func resolvePending(with result: PaspoAuthResult) {
        guard let pending else { return }
        self.pending = nil
        pending.timeoutTask?.cancel()
        pending.cancellationTask?.cancel()
        pending.continuation.resume(returning: result)
    }

    private func startTimeout() {
        guard pending != nil, configuration.callbackTimeout > 0 else { return }
        let timeout = configuration.callbackTimeout
        pending?.timeoutTask = Task { [weak self] in
            try? await Task.sleep(nanoseconds: UInt64(timeout * 1_000_000_000))
            guard Task.isCancelled == false else { return }
            self?.resolvePending(with: .failure(error: .sessionExpired, message: "No callback within \(timeout)s"))
        }
    }

    private func observeLifecycle() {
        #if canImport(UIKit)
        let center = NotificationCenter.default
        lifecycleObservers.tokens.append(
            center.addObserver(
                forName: UIApplication.didEnterBackgroundNotification,
                object: nil,
                queue: .main
            ) { [weak self] _ in
                Task { @MainActor [weak self] in self?.didLeaveApplication = true }
            }
        )
        lifecycleObservers.tokens.append(
            center.addObserver(
                forName: UIApplication.didBecomeActiveNotification,
                object: nil,
                queue: .main
            ) { [weak self] _ in
                Task { @MainActor [weak self] in self?.applicationDidBecomeActive() }
            }
        )
        #endif
    }

    /// The user came back without a callback ever arriving — Paspo ID was dismissed by
    /// swiping away or tapping the status-bar back button. Treat it as a cancellation, but
    /// only after a grace period: the callback URL may still be in flight.
    private func applicationDidBecomeActive() {
        guard pending != nil, didLeaveApplication else { return }
        didLeaveApplication = false

        let grace = configuration.cancellationGracePeriod
        pending?.cancellationTask?.cancel()
        pending?.cancellationTask = Task { [weak self] in
            try? await Task.sleep(nanoseconds: UInt64(max(0, grace) * 1_000_000_000))
            guard Task.isCancelled == false else { return }
            self?.resolvePending(with: .cancelled)
        }
    }
}

/// Holds notification tokens outside the actor so `deinit` can release them.
private final class LifecycleObserverBox {
    var tokens: [NSObjectProtocol] = []

    deinit {
        for token in tokens {
            NotificationCenter.default.removeObserver(token)
        }
    }
}
