import Foundation

/// URL contract between the client SDK and the Paspo ID app.
///
/// > Internal API. Declared public only so that the Paspo ID app can share it with the SDK;
/// > integrating applications must not rely on these values, they may change in any release.
public enum PaspoSSOConstants {
    /// Current version of the URL/envelope contract.
    public static let contractVersion = 1

    /// Custom scheme of the Paspo ID app.
    public static let paspoScheme = "paspo"
    /// Host of the authentication request URL.
    public static let ssoHost = "sso"

    /// Bundle identifier of the Paspo ID app (matches the Android package name `paspo.id`).
    public static let paspoBundleIdentifier = "paspo.id"

    // MARK: - Request parameters (client → Paspo)

    public enum RequestParameter {
        /// One-time value generated by the integrator's backend.
        public static let nonce = "nonce"
        /// Client's ephemeral X.509 (SubjectPublicKeyInfo) P-256 public key, base64url.
        public static let publicKey = "pub"
        /// Bundle identifier of the calling application.
        public static let bundleID = "pkgName"
        /// Requested ``PaspoScope`` key.
        public static let scope = "scope"
        /// Absolute URL Paspo ID opens to deliver the result, base64url of the UTF-8 URL string.
        public static let redirect = "redirect"
        /// Opaque per-request identifier echoed back in the callback.
        public static let state = "state"
        /// Nonce stored before an App Store redirect, used for install attribution.
        public static let referralNonce = "referral_nonce"
        /// Contract version.
        public static let version = "v"
    }

    // MARK: - Callback parameters (Paspo → client)

    public enum CallbackParameter {
        /// `success` | `error` | `cancelled`.
        public static let result = "paspo_result"
        /// Base64url of the ``PaspoEncryptedEnvelope`` JSON. Present when `result == success`.
        public static let data = "d"
        /// Numeric ``PaspoClientErrorCode``. Present when `result == error`.
        public static let errorCode = "error_code"
        /// The `state` value from the request.
        public static let state = "state"
        /// Contract version.
        public static let version = "v"
    }

    public enum CallbackResult {
        public static let success = "success"
        public static let error = "error"
        public static let cancelled = "cancelled"
    }

    /// Path Paspo ID appends to a client's redirect URL when *it* initiates sign-in
    /// (the analogue of Android's `paspo.id.ssoprovider.action.AUTHENTICATE` entry point).
    /// Supporting this entry point is optional.
    public static let signInRequestMarker = "paspo_signin"
}

/// Context strings for key derivation. Must stay byte-identical to the Android SDK.
public enum PaspoKDFContext {
    private static let version = "v1"
    private static let prefix = "paspo_id"

    /// Client → Paspo direction.
    public static let authRequest = "\(prefix)_auth_req_\(version)"
    /// Paspo → client direction.
    public static let authResponse = "\(prefix)_auth_res_\(version)"
}
